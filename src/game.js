// ========================================
// RANDOM CODE
// ========================================

export function randomCode() {
  const chars = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

  let result = "";

  for (let i = 0; i < 5; i++) {
    result += chars[Math.floor(Math.random() * chars.length)];
  }

  return result;
}

// ========================================
// RANDOM PICK
// ========================================

export function pick(array) {
  return array[Math.floor(Math.random() * array.length)];
}

// ========================================
// RANDOM ROUND TYPE
